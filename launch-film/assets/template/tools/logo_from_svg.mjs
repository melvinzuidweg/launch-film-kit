#!/usr/bin/env node
/*
 * Generate src/logo.js (window.LOGO) from a brand SVG, so the film draws the real logo geometry
 * as inline SVG (sharp at every zoom, animatable per part). Never edit src/logo.js by hand.
 *
 *   node tools/logo_from_svg.mjs assets/logo/logo.svg [--wordmark assets/logo/wordmark.svg] [--mono] [--out src/logo.js]
 *
 * --mono      recolour every fill/stroke that is not "none" to currentColor (the end card then
 *             paints the whole mark in --brand)
 * --wordmark  an outlined wordmark SVG (text as paths). Without it the end card sets
 *             COPY.end.name in Inter.
 *
 * window.LOGO = {
 *   viewBox: "minX minY w h",
 *   parts:   ["<path .../>", "<g>...</g>", ...],   top-level shapes in paint order; the end card
 *                                                   fades/scales each in at its final position
 *   defs:    "<defs>...</defs><style>...</style>",  carried over as is
 *   wordmark: null | { viewBox, inner },
 * }
 * Dependency-free on purpose (a small tag scanner, not a full XML parser): flatten exotic
 * markup in your editor first if the summary below looks wrong.
 */
import fs from "node:fs";
import path from "node:path";
import { ROOT, parseArgs } from "./lib.mjs";

const args = parseArgs();
const src = args._[0];
if (!src) { console.error("usage: node tools/logo_from_svg.mjs <logo.svg> [--wordmark wordmark.svg] [--mono] [--out src/logo.js]"); process.exit(2); }
const outFile = path.resolve(ROOT, typeof args.out === "string" ? args.out : "src/logo.js");

function readSvg(file) {
  let s = fs.readFileSync(path.resolve(ROOT, file), "utf8");
  s = s.replace(/<\?xml[\s\S]*?\?>/g, "").replace(/<!DOCTYPE[\s\S]*?>/gi, "").replace(/<!--[\s\S]*?-->/g, "");
  const open = s.match(/<svg\b[^>]*>/i);
  if (!open) throw new Error(`${file}: no <svg> element`);
  const attr = (name) => { const m = open[0].match(new RegExp(`\\s${name}\\s*=\\s*["']([^"']*)["']`, "i")); return m ? m[1] : null; };
  let viewBox = attr("viewBox");
  if (!viewBox) {
    const w = parseFloat(attr("width")), h = parseFloat(attr("height"));
    if (!(w > 0 && h > 0)) throw new Error(`${file}: <svg> has neither viewBox nor width/height`);
    viewBox = `0 0 ${w} ${h}`;
  }
  const start = open.index + open[0].length;
  const end = s.toLowerCase().lastIndexOf("</svg>");
  return { viewBox: viewBox.trim().replace(/[\s,]+/g, " "), inner: s.slice(start, end) };
}

// split the inner markup into top-level elements
function topLevel(inner) {
  const re = /<(\/?)([a-zA-Z][\w:.-]*)\b[^>]*?(\/?)>/g;
  const items = [];
  let depth = 0, startIdx = -1, name = "", m;
  while ((m = re.exec(inner))) {
    const [tagText, close, tag, selfClose] = m;
    if (!close && depth === 0) { startIdx = m.index; name = tag; }
    if (close) depth--;
    else if (!selfClose) depth++;
    if (depth === 0 && startIdx >= 0) {
      items.push({ name: name.toLowerCase(), text: inner.slice(startIdx, m.index + tagText.length) });
      startIdx = -1;
    }
  }
  return items;
}

const SKIP = new Set(["title", "desc", "metadata"]);
function mono(text) {
  return text
    .replace(/\s(fill|stroke)\s*=\s*["'](?!none)[^"']*["']/gi, ' $1="currentColor"')
    .replace(/(fill|stroke)\s*:\s*(?!none)[^;"']+/gi, "$1:currentColor");
}

const logo = readSvg(src);
let parts = [], defs = "";
for (const it of topLevel(logo.inner)) {
  if (SKIP.has(it.name) || it.name.includes(":")) continue;           // editor metadata (sodipodi:*, ...)
  if (it.name === "defs" || it.name === "style") { defs += it.text; continue; }
  parts.push(args.mono ? mono(it.text) : it.text);
}
if (!parts.length) { console.error(`${src}: no drawable top-level elements found`); process.exit(1); }

let wordmark = null;
if (typeof args.wordmark === "string") {
  const wm = readSvg(args.wordmark);
  const inner = topLevel(wm.inner).filter((it) => !SKIP.has(it.name) && !it.name.includes(":")).map((it) => it.text).join("");
  wordmark = { viewBox: wm.viewBox, inner: args.mono ? mono(inner) : inner };
}

const rel = (p) => path.relative(ROOT, path.resolve(ROOT, p)).replace(/\\/g, "/");
const data = { viewBox: logo.viewBox, parts, defs, wordmark };
const js = `/* Logo geometry, generated by tools/logo_from_svg.mjs from ${rel(src)}${wordmark ? ` and ${rel(args.wordmark)}` : ""}.
 * Do not edit by hand: replace the SVG and run the tool again. */
window.LOGO = ${JSON.stringify(data, null, 1)};
`;
fs.writeFileSync(outFile, js);
console.log(`wrote ${rel(outFile)}: viewBox "${logo.viewBox}", ${parts.length} part(s): ${parts.map((p) => p.match(/^<([\w:.-]+)/)[1]).join(", ")}${defs ? ", with defs/style" : ""}${wordmark ? ", with wordmark" : ""}`);
